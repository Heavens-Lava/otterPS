// otter-generator.js - Emits canonical, idiomatic Otter source code from the UI model

import { ComponentSchema } from '../model/schema.js';

export function generateOtterSource(uiModel) {
  const root = uiModel.getRoot();
  if (!root) return '# Empty Otter Application\n';

  const lines = [];
  const visited = new Set();

  lines.push(`# ===============================================================`);
  lines.push(`# Generated by Otter Studio`);
  lines.push(`# ===============================================================`);
  lines.push('');

  // 1. Create and configure the Root Window
  lines.push(`create window into ${root.name}`);
  const rootPropLines = formatProperties(root.properties, ComponentSchema['window']);
  if (rootPropLines.length > 0) {
    lines.push(`${root.name} has ${rootPropLines.join(', ')}`);
  }
  lines.push('');

  // 2. Walk the tree to declare components and configure them
  function declareSubtree(comp) {
    if (!comp) return;

    for (const childId of comp.children) {
      const child = uiModel.getComponent(childId);
      if (!child) continue;

      // Declaration
      lines.push(`create ${child.kind} into ${child.name}`);

      // Configuration
      const schema = ComponentSchema[child.kind] || {};
      const propLines = formatProperties(child.properties, schema);
      if (propLines.length > 0) {
        lines.push(`${child.name} has ${propLines.join(', ')}`);
      }

      lines.push('');

      // Recurse children
      if (child.children && child.children.length > 0) {
        declareSubtree(child);
      }
    }
  }

  declareSubtree(root);

  // 3. Put statements in hierarchical order
  function assemblePuts(comp) {
    if (!comp || !comp.children || comp.children.length === 0) return;

    // First assemble child containers
    for (const childId of comp.children) {
      const child = uiModel.getComponent(childId);
      if (child && child.children && child.children.length > 0) {
        assemblePuts(child);
      }
    }

    // Then put children into this container
    const childNames = comp.children
      .map(id => uiModel.getComponent(id))
      .filter(Boolean)
      .map(c => c.name);

    if (childNames.length > 0) {
      lines.push(`put ${childNames.join(', ')} in ${comp.name}`);
    }
  }

  assemblePuts(root);
  lines.push('');

  // 4. Event Handlers
  let hasEvents = false;
  for (const [id, events] of uiModel.events.entries()) {
    const comp = uiModel.getComponent(id);
    if (!comp) continue;

    for (const [eventKind, code] of Object.entries(events)) {
      if (!code || code.trim() === '') continue;
      hasEvents = true;

      lines.push(`when ${comp.name} is ${eventKind}`);
      const bodyLines = code.trim().split('\n');
      for (const line of bodyLines) {
        lines.push(`    ${line}`);
      }
      lines.push('.');
      lines.push('');
    }
  }

  // 5. Show Window
  lines.push(`show ${root.name}`);
  lines.push('');

  return lines.join('\n');
}

function formatProperties(props, schema) {
  const result = [];
  if (!props) return result;

  // Ordered priority for readable configuration
  const priority = [
    'title', 'text', 'placeholder', 'size', 'bold', 'italic',
    'width', 'height', 'spread', 'align', 'spacing', 'padding',
    'background', 'foreground', 'round', 'opacity', 'checked', 'value', 'source'
  ];

  const keys = Object.keys(props).sort((a, b) => {
    const ia = priority.indexOf(a);
    const ib = priority.indexOf(b);
    if (ia !== -1 && ib !== -1) return ia - ib;
    if (ia !== -1) return -1;
    if (ib !== -1) return 1;
    return a.localeCompare(b);
  });

  for (const key of keys) {
    const val = props[key];
    if (val === undefined || val === null || val === '') continue;

    // Format value according to Otter syntax rules
    if (typeof val === 'string') {
      if (key === 'width' && val === 'full') {
        result.push('width full');
      } else if (key === 'height' && val === 'full') {
        result.push('height full');
      } else if (key === 'spread' && val === true) {
        result.push('spread');
      } else if (key === 'align') {
        result.push(`align "${val}"`);
      } else {
        result.push(`${key} "${val}"`);
      }
    } else if (typeof val === 'boolean') {
      if (key === 'spread') {
        if (val) result.push('spread');
      } else if (key === 'bold') {
        if (val) result.push('bold true');
      } else if (key === 'italic') {
        if (val) result.push('italic true');
      } else if (key === 'checked') {
        result.push(`checked ${val}`);
      } else if (key === 'round') {
        if (val) result.push('round');
      }
    } else if (typeof val === 'number') {
      if (key === 'round') {
        result.push('round');
      } else {
        result.push(`${key} ${val}`);
      }
    }
  }

  return result;
}
