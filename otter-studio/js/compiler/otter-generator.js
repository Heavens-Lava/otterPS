// otter-generator.js - Emits canonical, idiomatic Otter source code from the UI model

import { ComponentSchema } from '../model/schema.js';

export function generateOtterSource(uiModel) {
  const root = uiModel.getRoot();
  if (!root) return '# Empty Otter Application\n';

  const lines = [];
  const visited = new Set();

  lines.push(`# ===============================================================`);
  lines.push(`# Generated by Otter Studio`);
  lines.push(`# ===============================================================`);
  lines.push('');

  // 1. Declare the root with Otter's declarative UI grammar.  This is the
  // same `name is a kind with ...` form emitted by the current web compiler;
  // Studio must not teach the older create-then-configure spelling by default.
  const rootPropLines = formatProperties(root.properties, ComponentSchema['window']);
  lines.push(declareComponent(root.name, uiModel.rootKind === 'page' ? 'page' : 'window', rootPropLines));
  lines.push('');

  // 2. Walk the tree to declare components and configure them
  function declareSubtree(comp) {
    if (!comp) return;

    for (const childId of comp.children) {
      const child = uiModel.getComponent(childId);
      if (!child) continue;

      // Declaration and configuration share one declarative statement.
      const schema = ComponentSchema[child.kind] || {};
      const propLines = formatProperties(child.properties, schema);
      lines.push(declareComponent(child.name, child.kind, propLines));

      lines.push('');

      // Recurse children
      if (child.children && child.children.length > 0) {
        declareSubtree(child);
      }
    }
  }

  declareSubtree(root);

  // 3. Put statements in hierarchical order
  function assemblePuts(comp) {
    if (!comp || !comp.children || comp.children.length === 0) return;

    // First assemble child containers
    for (const childId of comp.children) {
      const child = uiModel.getComponent(childId);
      if (child && child.children && child.children.length > 0) {
        assemblePuts(child);
      }
    }

    // Then put children into this container
    const childNames = comp.children
      .map(id => uiModel.getComponent(id))
      .filter(Boolean)
      .map(c => c.name);

    if (childNames.length > 0) {
      lines.push(`put ${childNames.join(', ')} in ${comp.name}`);
    }
  }

  assemblePuts(root);
  lines.push('');

  // 4. Event Handlers
  let hasEvents = false;
  for (const [id, events] of uiModel.events.entries()) {
    const comp = uiModel.getComponent(id);
    if (!comp) continue;

    for (const [eventKind, code] of Object.entries(events)) {
      if (!code || code.trim() === '') continue;
      hasEvents = true;

      lines.push(`when ${comp.name} is ${eventKind}`);
      for (const line of dedentBody(code)) {
        lines.push(line ? `    ${line}` : '');
      }
      lines.push('.');
      lines.push('');
    }
  }

  // 5. Show Window
  lines.push(`show ${root.name}`);
  lines.push('');

  return lines.join('\n');
}

// The Components panel's Heading is a large bold text: Otter 1.0 has no
// `heading` kind (SPEC-DECISIONS D56 leaves it post-1.0), so `x is a heading`
// compiled to nothing visible. It is written as the text it is (its size and
// bold go with it) and reads back as one.
const WRITTEN_KIND = { heading: 'text' };

/**
 * A handler body as its lines with the common indentation removed, so it
 * can be re-indented one level under `when`. Trimming the whole text only
 * removed the first line's indentation: every nested line then sat two
 * levels deeper than the first, which Otter rejects ("Indentation cannot
 * jump more than one level at a time").
 */
export function dedentBody(code) {
  const lines = String(code).replace(/\r\n?/g, '\n').split('\n');
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  const expanded = lines.map(line => line.replace(/\t/g, '    '));
  const indents = expanded.filter(line => line.trim()).map(line => line.match(/^ */)[0].length);
  const common = indents.length ? Math.min(...indents) : 0;
  return expanded.map(line => (line.trim() ? line.slice(common).replace(/\s+$/, '') : ''));
}

export function declareComponent(name, kind, propertyParts) {
  const prefix = `${name} is a ${WRITTEN_KIND[kind] || kind}`;
  // `x is a row` on its own opens a block of indented properties, so a
  // control with none would not compile: it keeps one of its defaults.
  let parts = propertyParts;
  if (parts.length === 0) {
    const defaults = ComponentSchema[kind]?.defaultProperties || {};
    for (const [key, value] of Object.entries(defaults)) {
      const part = formatProperty(key, value);
      if (part) { parts = [part]; break; }
    }
  }
  return parts.length > 0 ? `${prefix} with ${parts.join(', ')}` : prefix;
}

export function formatProperties(props, schema) {
  const result = [];
  if (!props) return result;

  // Ordered priority for readable configuration
  const priority = [
    'title', 'text', 'placeholder', 'size', 'weight', 'bold', 'italic',
    'width', 'height', 'spread', 'align', 'spacing', 'padding',
    'background', 'foreground', 'round', 'radius', 'pill', 'opacity', 'checked', 'value', 'source'
  ];

  const keys = Object.keys(props).sort((a, b) => {
    const ia = priority.indexOf(a);
    const ib = priority.indexOf(b);
    if (ia !== -1 && ib !== -1) return ia - ib;
    if (ia !== -1) return -1;
    if (ib !== -1) return 1;
    return a.localeCompare(b);
  });

  for (const key of keys) {
    const part = formatProperty(key, props[key]);
    if (part !== null) result.push(part);
  }

  return result;
}

/**
 * Format one property as Otter source (`text "Save"`, `width 400`, `spread`).
 * Returns null when the value means "not set" and nothing should be written
 * (empty values, and flags such as `spread` or `bold` that are false).
 * Shared by the full generator and the surgical splicer in source-splice.js,
 * so a designer edit writes a property exactly as a fresh file would.
 */
export function formatProperty(key, val) {
  if (val === undefined || val === null || val === '') return null;

  // Format value according to Otter syntax rules
  if (typeof val === 'string') {
    if (key === 'width' && val === 'full') return 'width full';
    if (key === 'height' && val === 'full') return 'height full';
    if (key === 'align') return `align "${val}"`;
    return `${key} "${val}"`;
  }
  if (typeof val === 'boolean') {
    if (key === 'spread') return val ? 'spread' : null;
    if (key === 'bold') return val ? 'bold true' : null;
    if (key === 'italic') return val ? 'italic true' : null;
    if (key === 'checked') return `checked ${val}`;
    // round: ordinary 8px corners; pill true: fully rounded ends (9999px).
    if (key === 'round') return val ? 'round' : null;
    if (key === 'pill') return val ? 'pill true' : null;
    // A page without the compiler's own title header (`hideheader true`).
    if (key === 'hideheader') return `hideheader ${val}`;
    // A row whose children move to the next line when there is no room.
    if (key === 'wrap') return val ? 'wrap true' : null;
    // A field its form will not send empty.
    if (key === 'required') return val ? 'required true' : null;
    return null;
  }
  if (typeof val === 'number') {
    // radius N: exactly N px corners.
    return `${key} ${val}`;
  }
  return null;
}
