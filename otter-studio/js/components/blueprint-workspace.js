// blueprint-workspace.js - Hybrid Visual + Code Blueprint Workspace for Otter Studio
// Implements Sections 3, 4, 6, 8, and 15 of Otter Blueprints Specification

export class BlueprintWorkspace {
  constructor(options = {}) {
    this.blueprint = options.blueprint || null;
    this.configValues = options.configValues || {};
    this.selectedNodeId = null;
    this.selectedEdgeId = null;
    this.explanationLevel = options.explanationLevel || 'intermediate'; // 'beginner' | 'intermediate' | 'advanced'
    this.sourceCode = '';
    this.isCustomized = false;
    this.onApplyBlueprint = options.onApplyBlueprint || (() => {});
    this.onRunChecks = options.onRunChecks || (() => {});
    this.sourceNodeRanges = new Map(); // nodeId -> { startLine, endLine }

    if (this.blueprint) {
      this.initFromBlueprint(this.blueprint);
    }
  }

  initFromBlueprint(bp) {
    this.blueprint = bp;
    this.configValues = {};
    if (bp.configuration) {
      for (const cfg of bp.configuration) {
        this.configValues[cfg.id] = cfg.default;
      }
    }
    this.selectedNodeId = bp.nodes && bp.nodes.length > 0 ? bp.nodes[0].id : null;
    this.selectedEdgeId = null;
    this.isCustomized = false;
    this.regenerateSource();
  }

  updateConfig(key, value) {
    this.configValues[key] = value;
    if (!this.isCustomized) {
      this.regenerateSource();
    }
  }

  setExplanationLevel(level) {
    if (['beginner', 'intermediate', 'advanced'].includes(level)) {
      this.explanationLevel = level;
    }
  }

  selectNode(nodeId) {
    this.selectedNodeId = nodeId;
    this.selectedEdgeId = null;
  }

  selectEdge(from, to) {
    this.selectedEdgeId = `${from}->${to}`;
    this.selectedNodeId = null;
  }

  // Generates ordinary, compatible Otter 1.0.1 code and records line source ranges
  regenerateSource() {
    if (!this.blueprint) {
      this.sourceCode = '';
      this.sourceNodeRanges.clear();
      return;
    }

    const lines = [];
    this.sourceNodeRanges.clear();

    lines.push(`# Generated by Otter Blueprint: ${this.blueprint.id} ${this.blueprint.version}`);
    lines.push(`# Standard editable Otter 1.0.1 source code`);
    lines.push('');

    // Package imports
    if (this.blueprint.packs && this.blueprint.packs.length > 0) {
      for (const p of this.blueprint.packs) {
        const parts = p.id.split('/');
        const pub = parts[0] || 'otter-official';
        const name = parts[1] || parts[0];
        lines.push(`use ".otter/packages/${pub}/${name}/${p.version}/src/main.ot"`);
      }
      lines.push('');
    }

    // Node-by-node code generation
    for (const node of (this.blueprint.nodes || [])) {
      const startLine = lines.length + 1;
      lines.push(`# Node: ${node.title || node.id} (${node.kind})`);

      if (node.id === 'enemyInit') {
        const hp = this.configValues['startingHealth'] || 100;
        lines.push(`enemyHp is ${hp}`);
        lines.push(`enemy is createActor "Dungeon Goblin" enemyHp 1`);
        lines.push(`say "Spawned enemy:" name of enemy "with" health of enemy "HP"`);
      } else if (node.id === 'attack') {
        const dmg = this.configValues['baseAttackDamage'] || 35;
        lines.push(`attackDmg is ${dmg}`);
        lines.push(`say "Player attacks delivering" attackDmg "damage!"`);
      } else if (node.id === 'applyDamage') {
        lines.push(`remHp is applyDamage enemy attackDmg`);
        lines.push(`say name of enemy "remaining HP:" remHp`);
      } else if (node.id === 'defeatCheck') {
        lines.push(`if remHp is at most 0`);
        lines.push(`    say "Defeat condition reached: Enemy down!"`);
        lines.push(`otherwise`);
        lines.push(`    say "Enemy withstands the blow and remains standing."`);
        lines.push(`.`);
      } else if (node.id === 'reward') {
        lines.push(`if remHp is at most 0`);
        lines.push(`    say "Reward awarded: 100 Experience Points"`);
        lines.push(`.`);
      } else if (node.kind === 'input') {
        lines.push(`inputValue is ${this.configValues['inputValue'] || 42}`);
      } else if (node.kind === 'pack-call') {
        lines.push(`result is ${node.capability || 'callFunction'} inputValue`);
        lines.push(`say "Result:" result`);
      } else {
        lines.push(`say "Step ${node.id} executed."`);
      }

      lines.push('');
      const endLine = lines.length;
      this.sourceNodeRanges.set(node.id, { startLine, endLine });
    }

    this.sourceCode = lines.join('\n');
  }

  // Generates side-effect-free BlueprintApplyPlan
  generatePlan(projectDir = '.') {
    if (!this.blueprint) throw new Error('No blueprint loaded.');

    const plannedFiles = (this.blueprint.generatedFiles || []).map(gf => ({
      path: gf.path,
      action: 'create',
      content: this.sourceCode
    }));

    const dependencies = (this.blueprint.packs || []).map(p => ({
      id: p.id,
      version: p.version
    }));

    return {
      blueprintId: this.blueprint.id,
      version: this.blueprint.version,
      title: this.blueprint.title,
      projectDir,
      plannedFiles,
      dependencies,
      configuration: { ...this.configValues }
    };
  }

  // Export diagram in Mermaid format for portable CLI or markdown viewing
  exportMermaid() {
    if (!this.blueprint) return '';
    const lines = ['graph LR'];
    for (const node of (this.blueprint.nodes || [])) {
      const label = `"${node.title || node.id}"`;
      lines.push(`    ${node.id}[${label}]`);
    }
    for (const edge of (this.blueprint.edges || [])) {
      const fromNode = edge.from.split('.')[0];
      const toNode = edge.to.split('.')[0];
      const edgeLabel = edge.label ? `|${edge.label}|` : '';
      lines.push(`    ${fromNode} -->${edgeLabel} ${toNode}`);
    }
    return lines.join('\n');
  }

  getExplanation() {
    if (!this.blueprint) return '';

    // If a node is selected, explain that node
    if (this.selectedNodeId) {
      const node = (this.blueprint.nodes || []).find(n => n.id === this.selectedNodeId);
      if (node) {
        if (this.explanationLevel === 'beginner') {
          return `Step '${node.title || node.id}': ${node.description || 'Executes this stage of the feature.'}`;
        }
        if (this.explanationLevel === 'intermediate') {
          const inPorts = (node.inputs || []).map(i => `${i.name} (${i.type})`).join(', ') || 'None';
          const outPorts = (node.outputs || []).map(o => `${o.name} (${o.type})`).join(', ') || 'None';
          return `Node: ${node.title} (${node.kind})\nCapability: ${node.capability || 'Built-in'}\nInputs: ${inPorts}\nOutputs: ${outPorts}\nPurpose: ${node.description || 'N/A'}`;
        }
        // Advanced
        const range = this.sourceNodeRanges.get(node.id);
        const lineInfo = range ? `Lines ${range.startLine}..${range.endLine}` : 'Unmapped';
        return `[Contract] Node '${node.id}' [${node.kind}]\nCapability: ${node.capability || 'core'}\nSource Mapping: ${lineInfo}\nDeterministic Purity: verified against Otter 1.0.1 grammar.`;
      }
    }

    // Global blueprint explanation
    const exp = this.blueprint.explanations || {};
    return exp[this.explanationLevel] || exp['intermediate'] || this.blueprint.summary || '';
  }

  render(containerEl) {
    if (!containerEl) return;
    this.container = containerEl;
    containerEl.className = 'blueprint-workspace-root';

    if (!this.blueprint) {
      containerEl.innerHTML = `
        <div class="blueprint-empty-state">
          <h3>No Blueprint Selected</h3>
          <p>Choose a Blueprint from the Library Explorer to inspect its data-flow wiring.</p>
        </div>
      `;
      return;
    }

    containerEl.innerHTML = `
      <div class="blueprint-toolbar">
        <div class="toolbar-left">
          <span class="bp-title">${this.escapeHtml(this.blueprint.title)}</span>
          <span class="bp-ver">v${this.escapeHtml(this.blueprint.version)}</span>
          ${this.isCustomized ? '<span class="bp-badge is-warning">Customized Source</span>' : '<span class="bp-badge is-clean">Synced</span>'}
        </div>
        <div class="toolbar-center">
          <label class="level-select-label">Explanation Mode:</label>
          <select id="bpExplLevelSelect">
            <option value="beginner" ${this.explanationLevel === 'beginner' ? 'selected' : ''}>Beginner</option>
            <option value="intermediate" ${this.explanationLevel === 'intermediate' ? 'selected' : ''}>Intermediate</option>
            <option value="advanced" ${this.explanationLevel === 'advanced' ? 'selected' : ''}>Advanced</option>
          </select>
        </div>
        <div class="toolbar-right">
          <button class="btn btn-secondary" id="btnBpExportMermaid">Export Diagram</button>
          <button class="btn btn-secondary" id="btnBpPreviewPlan">Preview Plan</button>
          <button class="btn btn-primary" id="btnBpApply">Apply Blueprint</button>
        </div>
      </div>

      <div class="blueprint-workspace-grid">
        <!-- Panel 1: Graph Canvas -->
        <div class="bp-panel bp-graph-panel">
          <div class="panel-header">
            <span>Visual Data-Flow Graph</span>
            <span class="panel-subtitle">${(this.blueprint.nodes || []).length} nodes, ${(this.blueprint.edges || []).length} connections</span>
          </div>
          <div class="bp-graph-canvas" id="bpGraphCanvas">
            ${this._renderGraphHtml()}
          </div>
        </div>

        <!-- Panel 2: Otter Source Editor View -->
        <div class="bp-panel bp-source-panel">
          <div class="panel-header">
            <span>Generated Otter Source</span>
            <span class="panel-file-tag">src/combat.ot</span>
          </div>
          <div class="bp-source-container">
            <textarea id="bpSourceEditor" spellcheck="false">${this.escapeHtml(this.sourceCode)}</textarea>
          </div>
        </div>

        <!-- Panel 3: Explain & Configuration Panel -->
        <div class="bp-panel bp-explain-panel">
          <div class="panel-header">
            <span>Blueprint Explanation & Config</span>
          </div>
          <div class="bp-explain-content">
            <div class="explain-text-box">
              <pre class="explain-text">${this.escapeHtml(this.getExplanation())}</pre>
            </div>
            
            ${this.blueprint.configuration && this.blueprint.configuration.length > 0 ? `
              <div class="bp-config-section">
                <h4>Parameters</h4>
                ${this.blueprint.configuration.map(cfg => `
                  <div class="config-row">
                    <label>${this.escapeHtml(cfg.label || cfg.id)}</label>
                    <input type="${cfg.type === 'number' ? 'number' : 'text'}" 
                           data-cfg="${this.escapeAttr(cfg.id)}" 
                           value="${this.escapeAttr(this.configValues[cfg.id])}" />
                  </div>
                `).join('')}
              </div>
            ` : ''}

            <div class="bp-dependencies-section">
              <h4>Dependencies (${(this.blueprint.packs || []).length})</h4>
              ${(this.blueprint.packs || []).map(p => `
                <div class="dep-pill">${this.escapeHtml(p.id)} v${this.escapeHtml(p.version)}</div>
              `).join('')}
            </div>
          </div>
        </div>
      </div>
    `;

    this._bindEvents();
  }

  _renderGraphHtml() {
    const nodes = this.blueprint.nodes || [];
    return `
      <div class="nodes-flow-container">
        ${nodes.map((n, idx) => {
          const isSelected = n.id === this.selectedNodeId;
          return `
            <div class="graph-node-card ${isSelected ? 'is-selected' : ''}" data-node-id="${this.escapeAttr(n.id)}">
              <div class="node-badge node-${n.kind}">${this.escapeHtml(n.kind)}</div>
              <div class="node-title">${this.escapeHtml(n.title || n.id)}</div>
              ${n.inputs && n.inputs.length > 0 ? `
                <div class="node-ports-in">
                  ${n.inputs.map(i => `<span class="port-in" title="In: ${i.type}">● ${i.name}</span>`).join(' ')}
                </div>
              ` : ''}
              ${n.outputs && n.outputs.length > 0 ? `
                <div class="node-ports-out">
                  ${n.outputs.map(o => `<span class="port-out" title="Out: ${o.type}">${o.name} ●</span>`).join(' ')}
                </div>
              ` : ''}
            </div>
            ${idx < nodes.length - 1 ? `<div class="flow-arrow">➔</div>` : ''}
          `;
        }).join('')}
      </div>
    `;
  }

  _bindEvents() {
    const levelSelect = this.container.querySelector('#bpExplLevelSelect');
    if (levelSelect) {
      levelSelect.addEventListener('change', (e) => {
        this.setExplanationLevel(e.target.value);
        this.render(this.container);
      });
    }

    const nodeCards = this.container.querySelectorAll('.graph-node-card');
    nodeCards.forEach(card => {
      card.addEventListener('click', () => {
        const nodeId = card.getAttribute('data-node-id');
        this.selectNode(nodeId);
        this.render(this.container);
      });
    });

    const cfgInputs = this.container.querySelectorAll('input[data-cfg]');
    cfgInputs.forEach(input => {
      input.addEventListener('change', (e) => {
        const key = input.getAttribute('data-cfg');
        const val = input.type === 'number' ? parseFloat(e.target.value) : e.target.value;
        this.updateConfig(key, val);
        this.render(this.container);
      });
    });

    const sourceEditor = this.container.querySelector('#bpSourceEditor');
    if (sourceEditor) {
      sourceEditor.addEventListener('input', (e) => {
        this.sourceCode = e.target.value;
        this.isCustomized = true;
        const badge = this.container.querySelector('.bp-badge');
        if (badge) {
          badge.className = 'bp-badge is-warning';
          badge.textContent = 'Customized Source';
        }
      });
    }

    const btnApply = this.container.querySelector('#btnBpApply');
    if (btnApply) {
      btnApply.addEventListener('click', () => {
        const plan = this.generatePlan();
        this.onApplyBlueprint(plan);
      });
    }

    const btnExport = this.container.querySelector('#btnBpExportMermaid');
    if (btnExport) {
      btnExport.addEventListener('click', () => {
        const m = this.exportMermaid();
        if (navigator.clipboard) {
          navigator.clipboard.writeText(m).then(() => alert('Mermaid diagram copied to clipboard!'));
        } else {
          console.log(m);
        }
      });
    }
  }

  escapeHtml(str) {
    if (str == null) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  escapeAttr(str) {
    if (str == null) return '';
    return String(str).replace(/"/g, '&quot;');
  }
}
